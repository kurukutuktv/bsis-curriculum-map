#!/usr/bin/env python3
"""
Regenerates the data files of the site from the sources.

    python3 build.py                 # uses ./roadmaps/*.json and ./curriculum_data.py
    python3 obtl_to_roadmap.py obtl/*.docx --out roadmaps && python3 build.py

Writes into ../js (the site at the repo root):  data.js, roadmaps/manifest.js, roadmaps/<SLUG>.js
"""
import os, json, glob, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import curriculum_data as cd

OUT = os.path.join(HERE, '..', 'js')
RM_OUT = os.path.join(OUT, 'roadmaps')
os.makedirs(RM_OUT, exist_ok=True)


def dump(o):
    return json.dumps(o, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')


with open(os.path.join(OUT, 'data.js'), 'w', encoding='utf8') as f:
    f.write('/* generated by source/build.py from curriculum_data.py (CMO No. 25, s. 2015) – do not edit */\n')
    f.write('window.CURRICULUM=' + dump(json.loads(cd.as_json())) + ';\n')

manifest = []
for fn in sorted(glob.glob(os.path.join(HERE, 'roadmaps', '*.json'))):
    d = json.load(open(fn, encoding='utf8'))
    weeks = [i for i in d['items'] if i['type'] == 'week']
    exams = [i for i in d['items'] if i['type'] == 'exam']
    hay = [d['code'], d['title']]
    for w in weeks:
        hay.append(w['ilo']); hay += w['topics']; hay += [a['text'] for a in w['at']]
    hay += [e['name'] for e in exams]
    manifest.append(dict(
        slug=d['slug'], code=d['code'], title=d['title'], term=d['term'], units=d['units'],
        weekGroups=len(weeks), topics=sum(len(w['topics']) for w in weeks),
        assessments=sum(len(w['at']) for w in weeks) + len(exams),
        hay=' \n '.join(x for x in hay if x)))
    with open(os.path.join(RM_OUT, d['slug'] + '.js'), 'w', encoding='utf8') as f:
        f.write('/* generated from %s – do not edit */\n' % d['source']['file'])
        f.write('(window.ROADMAPS=window.ROADMAPS||{})[%s]=%s;\n' % (json.dumps(d['slug']), dump(d)))

with open(os.path.join(RM_OUT, 'manifest.js'), 'w', encoding='utf8') as f:
    f.write('/* generated by source/build.py – list of available roadmaps */\n')
    f.write('window.ROADMAP_MANIFEST=' + dump(manifest) + ';\n')
print('data.js + %d roadmap(s): %s' % (len(manifest), ', '.join(m['slug'] for m in manifest)))
